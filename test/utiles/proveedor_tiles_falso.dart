/// Proveedor de tiles que nunca toca la red: cada tile es un PNG
/// transparente de 1x1. Cuenta cuántos tiles se pidieron.
class ProveedorTilesFalso extends TileProvider {
  int tilesPedidos = 0;

  @override
  ImageProvider getImage(TileCoordinates coordinates, TileLayer options) {
    tilesPedidos++;
    return MemoryImage(_pngTransparente);
  }
}

